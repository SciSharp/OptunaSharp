using System;
using System.Collections.Generic;
using OptunaSharp;
using OptunaSharp.Samplers;

namespace OptunaSharp.Benchmark.VolleyEval.Challenges;

/// <summary>
///     <b>Challenge 4 — the stochastic radical.</b> A rotated sphere observed through additive Gaussian
///     measurement noise (the BBOB-noisy family). This breaks the one assumption every earlier challenge
///     shares — <i>determinism</i>: the sampler never sees the true objective, only <c>f(x) + noise</c>,
///     so a single low observation can be a lucky noise draw rather than a genuinely good point.
///
///     <para>
///         <b>Objective the sampler optimizes:</b> <c>f_obs(x) = ‖Q·(x − x_opt)‖² + ε_t</c>, where
///         <c>ε_t ~ σ·N(0,1)</c> is drawn per trial. <b>Grading is on the truth:</b>
///         <see cref="Score" /> takes the point the sampler declared best (lowest <i>observed</i> value)
///         and reports the <i>noise-free</i> <c>f</c> there — so a noise-robust sampler that identifies a
///         genuinely good region wins, and one fooled by a lucky observation is penalized.
///     </para>
///
///     <para>
///         <b>Reproducible noise (common random numbers).</b> The noise vector is indexed by trial number
///         and re-drawn per run from the run seed (<see cref="Reset" />): every seed is an independent
///         noise realization, every run is bit-reproducible, and two samplers face the same noise at the
///         same trial index (variance-reducing common random numbers). Optimum <c>0</c> at
///         <c>x = x_opt</c>; random baseline = the noise-free uniform mean (noise is zero-mean).
///     </para>
/// </summary>
public sealed class NoisySphere : IChallenge
{
    private readonly double[] _shift;
    private readonly double[,] _q;
    private readonly double _sigma;
    private double[] _noise; // per-trial noise, regenerated by Reset(seed)

    /// <param name="dimension">D (v0: 10 — low enough to keep GP viable, high enough to be non-trivial).</param>
    /// <param name="sigma">Noise standard deviation (v0: 8 — heavy enough that rank-based robustness clearly separates from density/model methods).</param>
    /// <param name="instanceId">Seeds the rotation and shift.</param>
    /// <param name="budget">Per-run trial budget; sizes the noise vector.</param>
    public NoisySphere(int dimension = 10, double sigma = 8.0, int instanceId = 0, int budget = 300)
    {
        Dimension = dimension;
        InstanceId = instanceId;
        Budget = budget;
        _sigma = sigma;
        (_shift, _q) = BuildInstance(dimension, instanceId);
        RandomBaseline = EstimateUniformMean(dimension, instanceId, _shift, _q);
        _noise = Array.Empty<double>();
        Reset(0); // give a valid noise vector even before the Evaluator re-seeds per run
    }

    /// <inheritdoc />
    public string Name => "noisy_sphere";

    /// <inheritdoc />
    public IReadOnlyList<string> Tags => new[] { "continuous", "noisy", "stochastic", "single-obj" };

    /// <inheritdoc />
    public int Dimension { get; }

    /// <inheritdoc />
    public int NumObjectives => 1;

    /// <inheritdoc />
    public IReadOnlyList<StudyDirection> Directions => new[] { StudyDirection.Minimize };

    /// <inheritdoc />
    public int InstanceId { get; }

    /// <summary>Exact minimum of the (noise-free) sphere.</summary>
    public double Optimum => 0.0;

    /// <inheritdoc />
    public double RandomBaseline { get; }

    /// <inheritdoc />
    public IReadOnlyList<double> ReferencePoint => Array.Empty<double>();

    /// <inheritdoc />
    public int Budget { get; }

    /// <summary>Stochastic + continuous — the inert (≡ random) check does not apply.</summary>
    public bool DetectInert => false;

    /// <summary>Re-draw the per-trial noise from the run seed (independent realization, reproducible).</summary>
    public void Reset(int seed)
    {
        var rng = new LazyRandomState(30000 + seed).Rng;
        var noise = new double[Budget];
        for (int t = 0; t < Budget; t++)
            noise[t] = _sigma * rng.randn<double>();
        _noise = noise;
    }

    /// <inheritdoc />
    public IReadOnlyList<double> Evaluate(Trial trial)
    {
        var x = new double[Dimension];
        for (int i = 0; i < Dimension; i++)
            x[i] = trial.SuggestFloat($"x{i}", -5.0, 5.0);
        // The sampler sees the noisy observation; the noise is fixed per trial index for this run.
        double noise = trial.Number < _noise.Length ? _noise[trial.Number] : 0.0;
        return new[] { TrueValue(x) + noise };
    }

    /// <summary>The noise-free sphere value ‖Q·(x − x_opt)‖². Exposed for tests / scoring.</summary>
    public double TrueValue(double[] x)
    {
        int d = Dimension;
        double f = 0.0;
        for (int i = 0; i < d; i++)
        {
            double z = 0.0;
            for (int k = 0; k < d; k++) z += _q[i, k] * (x[k] - _shift[k]);
            f += z * z;
        }
        return f;
    }

    /// <summary>The exact optimum location x_opt (a copy), for tests.</summary>
    public double[] OptimumLocation() => (double[])_shift.Clone();

    /// <inheritdoc />
    public double Score(Study study)
    {
        // Grade the TRUE objective at the point the sampler believed was best (lowest noisy observation).
        var best = study.BestTrial;
        var x = new double[Dimension];
        for (int i = 0; i < Dimension; i++)
            x[i] = Convert.ToDouble(best.Params[$"x{i}"], System.Globalization.CultureInfo.InvariantCulture);
        return (RandomBaseline - TrueValue(x)) / (RandomBaseline - Optimum);
    }

    private static (double[] shift, double[,] q) BuildInstance(int d, int instanceId)
    {
        var rng = new LazyRandomState(3000 + instanceId).Rng;
        var shift = new double[d];
        for (int i = 0; i < d; i++) shift[i] = (double)rng.uniform(-3.0, 3.0);

        var a = new double[d, d];
        for (int i = 0; i < d; i++)
            for (int j = 0; j < d; j++)
                a[i, j] = rng.randn<double>();

        var q = new double[d, d];
        for (int j = 0; j < d; j++)
        {
            var v = new double[d];
            for (int i = 0; i < d; i++) v[i] = a[i, j];
            for (int k = 0; k < j; k++)
            {
                double dot = 0.0;
                for (int i = 0; i < d; i++) dot += q[i, k] * a[i, j];
                for (int i = 0; i < d; i++) v[i] -= dot * q[i, k];
            }
            double norm = 0.0;
            for (int i = 0; i < d; i++) norm += v[i] * v[i];
            norm = Math.Sqrt(norm);
            for (int i = 0; i < d; i++) q[i, j] = v[i] / norm;
        }
        return (shift, q);
    }

    private double EstimateUniformMean(int d, int instanceId, double[] shift, double[,] q)
    {
        var rng = new LazyRandomState(9500 + instanceId).Rng;
        const int samples = 20_000;
        double sum = 0.0;
        var x = new double[d];
        for (int t = 0; t < samples; t++)
        {
            for (int i = 0; i < d; i++) x[i] = (double)rng.uniform(-5.0, 5.0);
            sum += TrueValue(x);
        }
        return sum / samples;
    }
}
